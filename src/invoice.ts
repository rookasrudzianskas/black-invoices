export const ibanCheck = (
  value: string,
  countryCode: string,
): ValidationHint => {
  const country = getTaxCountry(countryCode);
  const iban = normalizeIban(value);

  if (!country.ibanLength) {
    return {
      code: "iban-unavailable",
      message:
        "IBAN is not registered for this country; use local bank details plus SWIFT/BIC.",
      tone: "warning",
    };
  }

  if (!iban) {
    return {
      code: "iban-empty",
      message: `${country.name} IBANs are ${country.ibanLength} characters.`,
      tone: "warning",
    };
  }

  if (!iban.startsWith(country.code)) {
    return {
      code: "iban-prefix",
      message: `Expected an IBAN starting with ${country.code}.`,
      tone: "warning",
    };
  }

  if (iban.length !== country.ibanLength) {
    return {
      actualLength: iban.length,
      code: "iban-length",
      message: `${country.name} IBANs are ${country.ibanLength} characters; this one has ${iban.length}.`,
      tone: "warning",
    };
  }

  return {
    code: "iban-valid",
    message: `${country.name} IBAN format looks right.`,
    tone: "success",
  };
};

export const ibanHint = (value: string, countryCode: string) =>
  ibanCheck(value, countryCode).message;

export const bicCheck = (value: string): ValidationHint => {
  const bic = normalizeBic(value);

  if (!bic) {
    return {
      code: "bic-empty",
      message: "Add BIC/SWIFT for cross-border bank transfers.",
      tone: "warning",
    };
  }

  if (!/^[A-Z]{4}[A-Z]{2}[A-Z0-9]{2}([A-Z0-9]{3})?$/.test(bic)) {
    return {
      code: "bic-invalid",
      message: "BIC/SWIFT should be 8 or 11 characters, for example ESSESESS.",
      tone: "warning",
    };
  }

  return {
    code: "bic-valid",
    message: "BIC/SWIFT format looks right.",
    tone: "success",
  };
};

export function formatDate(value: string, countryCode?: string) {
  if (!value) {
    return "";
  }

  const [year, month, day] = value.split("-");
  if (!year || !month || !day) {
    return value;
  }

  const date = new Date(Date.UTC(Number(year), Number(month) - 1, Number(day)));

  if (Number.isNaN(date.getTime())) {
    return value;
  }

  return new Intl.DateTimeFormat(
    countryCode ? getTaxCountry(countryCode).locale : "en-IE",
    {
      day: "2-digit",
      month: "2-digit",
      timeZone: "UTC",
      year: "numeric",
    },
  )
    .format(date)
    .replace(/\u00a0/g, " ");
}

export const formatCurrency = (
  value: number,
  options: { countryCode?: string; decimals?: number; grouped?: boolean } = {},
) => {
  const safeValue = Number.isFinite(value) ? value : 0;
  const decimals = options.decimals ?? 0;
  const grouped = options.grouped ?? true;
  const locale = options.countryCode
    ? getTaxCountry(options.countryCode).locale
    : "en-IE";

  return new Intl.NumberFormat(locale, {
    currency: "EUR",
    currencyDisplay: "symbol",
    style: "currency",
    useGrouping: grouped,
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })
    .format(safeValue)
    .replace(/\u00a0/g, " ");
};

