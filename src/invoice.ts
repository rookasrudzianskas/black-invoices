export const getInvoiceCopy = (
  countryCode: string,
  mode: InvoiceLanguageMode,
): InvoiceCopy => {
  const country = getTaxCountry(countryCode);

  if (mode === "local") {
    return {
      ...country.localCopy,
      taxId: country.localCopy.taxId || country.taxIdLabel,
      taxName: country.localCopy.taxName || country.taxName,
    };
  }

  return {
    ...ENGLISH_INVOICE_COPY,
    taxId: country.taxIdLabel,
    taxName: country.taxName,
  };
};

export const getAppCopy = (
  countryCode: string,
  mode: InvoiceLanguageMode,
): AppCopy => (mode === "local" ? getTaxCountry(countryCode).localAppCopy : ENGLISH_APP_COPY);

export const countryDisplayName = (
  code: string,
  displayCountryCode: string,
  mode: InvoiceLanguageMode,
) => {
  const country = getTaxCountry(code);

  if (mode === "english") {
    return country.name;
  }

  try {
    const displayNames = new Intl.DisplayNames([getTaxCountry(displayCountryCode).locale], {
      type: "region",
    });

    return displayNames.of(code) ?? country.name;
  } catch {
    return country.name;
  }
};

export const paymentRailLabel = (
  countryCode: string,
  mode: InvoiceLanguageMode,
) => {
  const copy = getAppCopy(countryCode, mode);

  if (SEPA_COUNTRY_CODES.has(countryCode)) {
    return copy.sepaTransfer;
  }

  return countryCode === "RU" ? copy.localSwiftTransfer : copy.ibanSwiftTransfer;
};

export const duePresetLabel = (
  days: number,
  countryCode: string,
  mode: InvoiceLanguageMode,
) => {
  const copy = getAppCopy(countryCode, mode);

  if (days === 0) {
    return copy.dueToday;
  }

  return days === 1 ? copy.dueInDay : copy.dueInDays(days);
};

export const formatIbanValidation = (
  hint: ValidationHint,
  countryCode: string,
  mode: InvoiceLanguageMode,
) => {
  const country = getTaxCountry(countryCode);
  const copy = getAppCopy(countryCode, mode);
  const countryName = countryDisplayName(countryCode, countryCode, mode);

  if (hint.code === "iban-unavailable") {
    return copy.ibanUnavailable(countryName);
  }

  if (hint.code === "iban-empty" && country.ibanLength) {
    return copy.ibanEmpty(countryName, country.ibanLength);
  }

  if (hint.code === "iban-prefix") {
    return copy.ibanPrefix(country.code);
  }

  if (hint.code === "iban-length" && country.ibanLength) {
    return copy.ibanLength(countryName, country.ibanLength, hint.actualLength ?? 0);
  }

  if (hint.code === "iban-valid") {
    return copy.ibanValid(countryName);
  }

  return hint.message;
};

