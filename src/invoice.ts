const sameRecord = <Value extends Record<string, string | number>>(
  left: Value,
  right: Value,
) =>
  Object.keys(left).every(
    (key) => left[key as keyof Value] === right[key as keyof Value],
  );

export const invoiceWithCountryExamples = (
  invoice: InvoiceData,
  nextCountryCode: string,
): InvoiceData => {
  const previousCountry = getTaxCountry(invoice.taxCountryCode);
  const nextCountry = getTaxCountry(nextCountryCode);
  const previousItem = previousCountry.examples.item;
  const nextItem = nextCountry.examples.item;
  const previousTerms = paymentTermsForDueDate(
    invoice.dueDate,
    previousCountry.code,
    invoice.languageMode,
  );
  const previousEnglishTerms = paymentTermsForDueDate(
    invoice.dueDate,
    previousCountry.code,
    "english",
  );
  const previousLocalTerms = paymentTermsForDueDate(
    invoice.dueDate,
    previousCountry.code,
    "local",
  );
  const nextTerms = paymentTermsForDueDate(
    invoice.dueDate,
    nextCountry.code,
    "local",
  );
  const shouldSwapTerms = [
    previousCountry.examples.payment.terms,
    previousTerms,
    previousEnglishTerms,
    previousLocalTerms,
  ].includes(invoice.payment.terms);
  const shouldSwapPayment =
    invoice.payment.beneficiary === previousCountry.examples.payment.beneficiary &&
    invoice.payment.bank === previousCountry.examples.payment.bank &&
    invoice.payment.iban === previousCountry.examples.payment.iban &&
    invoice.payment.bic === previousCountry.examples.payment.bic &&
    invoice.payment.reference === invoice.invoiceNo &&
    [previousCountry.examples.payment.terms, previousTerms].includes(
      invoice.payment.terms,
    );

  return {
    ...invoice,
    taxCountryCode: nextCountry.code,
    languageMode: "local",
    from: sameRecord(invoice.from, previousCountry.examples.from)
      ? nextCountry.examples.from
      : invoice.from,
    to: sameRecord(invoice.to, previousCountry.examples.to)
      ? nextCountry.examples.to
      : invoice.to,
    items: invoice.items.map((item, index) =>
      index === 0 &&
      item.item === previousItem.item &&
      item.quantity === previousItem.quantity &&
      item.price === previousItem.price
        ? { ...item, ...nextItem }
        : item,
    ),
    payment: shouldSwapPayment
      ? {
          ...nextCountry.examples.payment,
          reference: invoice.invoiceNo,
          terms: nextTerms,
        }
      : {
          ...invoice.payment,
          terms: shouldSwapTerms ? nextTerms : invoice.payment.terms,
        },
  };
};

